#!/usr/bin/env python3
"""Aggregation analysis (Section 6 machinery) on the executed-system example
(Section 8) - the compute task promised to Giudici on 2026-08-13.

INTERNAL WORKING ARTIFACT. This file names repositories, hosts, and project
codenames for reproducibility. None of those names may appear in the
manuscript or in any article-facing text. In the article the substrate is
described only as "a live agentic research pipeline operated by the first
author".

WHY THIS EXISTS. The frozen executed-system run (real-agentic-2026-07-25,
run of record 2026-07-27) stored, per bootstrap replicate, only the three
SCALAR metrics per (stage, model) arm. The volume-integration composites
(arithmetic / geometric / RMS, Kolesnikov's construction) and the TOPSIS
closeness coefficient consume the three CURVES on a severity grid, which
that run did not store. This harness rebuilds the curves per replicate,
deterministically, and computes the aggregation analysis parallel to the
Section 6 study (pavia-composite-2026-07-25), so that Section 8 can carry
the same table for the executed system.

PROVENANCE AND VALIDATION GATES (all hard-fail):
  G1  the episode table is read from the frozen episodes-real-agentic.csv;
      the train/eval split is regenerated by the identical seeded
      train_test_split call and must reproduce the CSV's split column.
  G2  the retrained scorers must reproduce the frozen run's stored
      p_full_{stage}_{model} and y_eval_{stage} bit-for-bit (npz).
  G3  the frozen run's paired_fixed_{stage}_{model} scalar replicate
      matrices (B x 3) and point vectors must be reproduced bit-for-bit
      from the same seeded precompute + bootstrap streams.
  G4  the fast bootstrap curve path must match the pinned package's own
      rga_curve / rge_curve at the point estimate (pavia fastpath check).

CURVE CONVENTIONS are imported from the Section 6 study module itself
(pavia_composite_experiment.py, loaded by path, sha256 recorded), not
copied, so the two studies cannot drift: severity grid s_t = t/GRID with
GRID = d = 9, curve length L = 10; RGA = accumulated partial curve
(curve_method='partial'); RGE = greedy monotone removal curve; RGR study
family = the article's tail-swap, control family = scaled Gaussian noise
(sigma_t = t/GRID, scaled by column std). Composites and the delta-method
cross-term decomposition come from the same module (arm_block).

NEW RANDOMNESS in this study (documented, seeded): the independent-stream
index matrices IND[k] use default_rng(SEED + 10 + k), k = 0,1,2 - the
Section 6 study's rule; the Gaussian control predictions use a fresh
default_rng(SEED) per (stage, model) arm in the documented arm order.
The paired bootstrap index stream is NOT new: default_rng(SEED + 1)
re-instantiated per arm, exactly the frozen run's rule (G3 proves it).

Run:
  python3 aggregation_harness.py --tag pilot        # B=200, logit arms only
  python3 aggregation_harness.py --tag production   # B=2000, all 4 arms
"""
import argparse
import csv
import hashlib
import importlib.util
import json
import math
import os
import sys
import time
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.normpath(os.path.join(HERE, ".."))
REAL = os.path.join(EXP, "real-agentic-2026-07-25")
PAVIA_PATH = os.path.join(EXP, "pavia-composite-2026-07-25",
                          "pavia_composite_experiment.py")
REDRAW_DIR = os.path.join(EXP, "redraw-2026-07-24")
sys.path.insert(0, os.path.join(REDRAW_DIR, "_stubs"))
sys.path.insert(0, os.path.join(REDRAW_DIR, "safeai-src"))

import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from safeai.rga import rga_score
from safeai.rge import rge_score
from safeai.rgr import rgr_score

# ---- the Section 6 study module, loaded by path so conventions cannot drift
spec = importlib.util.spec_from_file_location("pavia", PAVIA_PATH)
pavia = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pavia)

# ---- constants of the frozen executed-system run (harness.py of record)
SEED = 20260727
NOISE_SD = 0.5
ALPHA = 0.05
STAGES = ["A", "B"]
MODEL_TAGS = ["logit", "rf"]
FEATURES_A = ["tool_code", "log10_amount", "payee_unknown", "n_methods_allowed",
              "log10_cap", "headroom_frac", "method_in_scope",
              "expiry_margin_s", "issuer_on_list"]
FEATURES_B = ["tool_code", "log10_amount", "payee_unknown", "headroom_frac",
              "expiry_margin_s", "issuer_on_list", "n_package_fields",
              "nonce_match", "ear_nonce_match"]
CLASS_ORDER = np.array([0, 1])

LOG = []


def say(msg=""):
    print(msg, flush=True)
    LOG.append(msg)


def safeai_commit():
    """The commit the imported safeai actually resolves to. Read from the
    clone's git metadata; hard-fail rather than guess — an invented pin is
    worse than a missing one."""
    src = os.path.dirname(os.path.dirname(
        os.path.abspath(sys.modules["safeai.rga"].__file__)))
    head_path = os.path.join(src, ".git", "HEAD")
    with open(head_path, encoding="ascii") as fh:
        head = fh.read().strip()
    if head.startswith("ref: "):
        ref = os.path.join(src, ".git", *head[5:].split("/"))
        with open(ref, encoding="ascii") as fh:
            head = fh.read().strip()
    if not (len(head) == 40 and all(c in "0123456789abcdef" for c in head)):
        raise RuntimeError(f"cannot resolve safeai commit from {head_path}")
    return head


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_episodes():
    rows = list(csv.DictReader(open(os.path.join(REAL,
                                                 "episodes-real-agentic.csv"))))
    rows.sort(key=lambda r: int(r["i"]))
    N = len(rows)
    X_A = np.array([[float(r[f"fA_{f}"]) for f in FEATURES_A] for r in rows])
    X_B = np.array([[float(r[f"fB_{f}"]) for f in FEATURES_B] for r in rows])
    y_A = np.array([int(r["yA"]) for r in rows])
    y_B = np.array([int(r["yB"]) for r in rows])
    split = np.array([r["split"] for r in rows])
    return N, X_A, X_B, y_A, y_B, split


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", choices=["pilot", "production"], required=True)
    args = ap.parse_args()
    B = 200 if args.tag == "pilot" else 2000
    model_tags = ["logit"] if args.tag == "pilot" else MODEL_TAGS
    t_start = time.time()

    say(f"[config] tag={args.tag} B={B} arms={[f'{s}_{m}' for s in STAGES for m in model_tags]}")
    say(f"[pin] pavia module sha256 {sha256_file(PAVIA_PATH)}")
    say(f"[pin] frozen npz sha256 {sha256_file(os.path.join(REAL, 'replicates-real-agentic.npz'))}")

    # ---- G1: rebuild data + the seeded split, check against the CSV column ----
    N, X_A, X_B, y_A, y_B, split_col = load_episodes()
    y_cell = 2 * y_A + y_B
    n_eval = 300
    idx_all = np.arange(N)
    idx_tr, idx_te = train_test_split(idx_all, test_size=n_eval,
                                      random_state=SEED, stratify=y_cell)
    csv_eval = set(np.where(split_col == "eval")[0].tolist())
    if set(idx_te.tolist()) != csv_eval:
        raise SystemExit("G1 FAIL: regenerated eval split != CSV split column")
    say(f"[G1] split reproduced: N={N} train={len(idx_tr)} eval={len(idx_te)} "
        f"== CSV split column")

    X = {"A": X_A, "B": X_B}
    y = {"A": y_A, "B": y_B}
    Xtr = {s: X[s][idx_tr] for s in STAGES}
    Xte = {s: X[s][idx_te] for s in STAGES}
    ytr = {s: y[s][idx_tr] for s in STAGES}
    yte = {s: y[s][idx_te] for s in STAGES}
    n = n_eval

    # ---- G2: retrain scorers, reproduce stored y_eval and p_full exactly ----
    frozen = np.load(os.path.join(REAL, "replicates-real-agentic.npz"))
    models = {}
    for s in STAGES:
        if not np.array_equal(yte[s], frozen[f"y_eval_{s}"]):
            raise SystemExit(f"G2 FAIL: y_eval_{s} differs from the frozen run")
        for m in MODEL_TAGS:
            if m == "logit":
                mod = make_pipeline(StandardScaler(),
                                    LogisticRegression(max_iter=2000,
                                                       random_state=SEED))
            else:
                mod = RandomForestClassifier(n_estimators=300,
                                             random_state=SEED, n_jobs=-1)
            mod.fit(Xtr[s], ytr[s])
            models[(s, m)] = mod
            p = mod.predict_proba(Xte[s])[:, 1]
            gap = float(np.max(np.abs(p - frozen[f"p_full_{s}_{m}"])))
            if gap > 1e-12:
                raise SystemExit(f"G2 FAIL: p_full_{s}_{m} max abs gap {gap:.3e}")
            say(f"[G2] p_full_{s}_{m} reproduced, max abs gap {gap:.1e}")

    # ---- G3: reproduce the frozen scalar replicate matrices bit-for-bit ----
    # precompute in the frozen run's documented order, sharing one rng stream
    pre = {}
    rng_global = np.random.default_rng(SEED)
    for s in STAGES:
        for m in MODEL_TAGS:
            mod = models[(s, m)]
            Xt = Xte[s]
            p_full = mod.predict_proba(Xt)[:, 1]
            d = Xt.shape[1]
            col_mean = Xt.mean(axis=0)
            col_std = Xt.std(axis=0, keepdims=True)
            p_masked = np.empty((d, n))
            for j in range(d):
                Xm = Xt.copy()
                Xm[:, j] = col_mean[j]
                p_masked[j] = mod.predict_proba(Xm)[:, 1]
            pert = rng_global.normal(0.0, NOISE_SD, size=Xt.shape) * col_std
            p_pert_fixed = mod.predict_proba(Xt + pert)[:, 1]
            pre[(s, m)] = (p_full, p_masked, p_pert_fixed, col_mean, col_std)

    def metric_vector_fixed(s, m, idx):
        p_full, p_masked, p_pert_fixed = pre[(s, m)][:3]
        yb, pf = yte[s][idx], p_full[idx]
        rga = rga_score(yb, pf)
        rge = float(np.mean([rge_score(pf, p_masked[j][idx])
                             for j in range(p_masked.shape[0])]))
        rgr = rgr_score(pf, p_pert_fixed[idx])
        return np.array([rga, rge, rgr])

    B_frozen = frozen["paired_fixed_A_logit"].shape[0]
    for s in STAGES:
        for m in MODEL_TAGS:
            point = metric_vector_fixed(s, m, np.arange(n))
            gp = float(np.max(np.abs(point - frozen[f"point_{s}_{m}"])))
            boot_rng = np.random.default_rng(SEED + 1)
            gmax = 0.0
            for b in range(B_frozen):
                idx = boot_rng.integers(0, n, n)
                vec = metric_vector_fixed(s, m, idx)
                gmax = max(gmax, float(np.max(np.abs(
                    vec - frozen[f"paired_fixed_{s}_{m}"][b]))))
            if gp > 0.0 or gmax > 0.0:
                if gp > 1e-13 or gmax > 1e-13:
                    raise SystemExit(f"G3 FAIL {s}_{m}: point gap {gp:.3e}, "
                                     f"replicate gap {gmax:.3e}")
            say(f"[G3] paired_fixed_{s}_{m}: point gap {gp:.1e}, "
                f"max replicate gap over B={B_frozen}: {gmax:.1e}")
    say(f"[gates] G1-G3 passed at {time.time() - t_start:.1f}s")

    # ---- shared bootstrap index streams for the curve study ----
    IDX = np.empty((B, n), dtype=np.int64)
    boot_rng = np.random.default_rng(SEED + 1)      # the frozen run's rule
    for b in range(B):
        IDX[b] = boot_rng.integers(0, n, n)
    IND = np.empty((3, B, n), dtype=np.int64)
    for k in range(3):
        rk = np.random.default_rng(SEED + 10 + k)   # Section 6 study's rule
        for b in range(B):
            IND[k, b] = rk.integers(0, n, n)

    GRID = 9
    L = GRID + 1
    say(f"[grid] severity s_t = t/{GRID}, t = 0..{GRID} -> curve length L = {L}")
    pis, nis = pavia.topsis_reference(L)
    wvec = np.concatenate([np.full(L, 1.0 / 3.0)] * 3)

    results = {
        "purpose": "Section 8 aggregation analysis parallel to Section 6",
        "tag": args.tag, "B": B, "alpha": ALPHA, "seed": SEED,
        "grid": GRID, "curve_length_L": L,
        "index_streams": {
            "paired_bootstrap": "default_rng(SEED+1) per arm (frozen run's rule; G3)",
            "independent_streams": "default_rng(SEED+10+k), k=0,1,2 (Section 6 rule)",
            "gaussian_control_rng": "default_rng(SEED) fresh per arm, arm order "
                                    "A_logit, A_rf, B_logit, B_rf",
        },
        "pins": {
            "pavia_module_sha256": sha256_file(PAVIA_PATH),
            "frozen_npz_sha256": sha256_file(
                os.path.join(REAL, "replicates-real-agentic.npz")),
            "episodes_csv_sha256": sha256_file(
                os.path.join(REAL, "episodes-real-agentic.csv")),
            "safeai_commit": safeai_commit(),
        },
        "numpy_version": np.__version__,
        "generated_utc": datetime.now(timezone.utc).isoformat(
            timespec="seconds"),
        "gates": "G1 split, G2 y/p_full, G3 scalar replicates: all bit-level",
        "arms": {},
    }

    from safeai.rga import rga_curve  # noqa: F401  (used via pavia.rga_vector)

    for s in STAGES:
        for m in model_tags:
            arm = f"{s}_{m}"
            t_arm = time.time()
            mod = models[(s, m)]
            Xt = Xte[s]
            yt = yte[s]
            names = FEATURES_A if s == "A" else FEATURES_B
            p_full, _, _, col_mean, col_std = pre[(s, m)]

            # ---- point curves via the package (Section 6 conventions)
            a0 = pavia.rga_vector(yt, p_full, GRID)
            e0, order = pavia.rge_vector_package(mod, Xt, names, GRID, "mean")
            ps = 0.5 * np.arange(L) / GRID
            r0_swap = np.empty(L)
            for t in range(L):
                r0_swap[t] = rgr_score(
                    p_full, mod.predict_proba(pavia.tail_swap(Xt, ps[t]))[:, 1],
                    class_order=CLASS_ORDER)

            # ---- precompute prediction matrices for the fast bootstrap path
            p_mask = np.empty((L, n))
            p_mask[0] = p_full
            for t in range(1, L):
                Xm = Xt.copy()
                cols = order[:t]
                Xm[:, cols] = col_mean[cols]
                p_mask[t] = mod.predict_proba(Xm)[:, 1]
            p_swap = np.empty((L, n))
            for t in range(L):
                p_swap[t] = mod.predict_proba(pavia.tail_swap(Xt, ps[t]))[:, 1]
            rng_noise = np.random.default_rng(SEED)
            p_noise = np.empty((L, n))
            for t in range(L):
                sigma = t / float(GRID)
                Xp = (Xt + rng_noise.normal(0.0, sigma, size=Xt.shape) * col_std
                      if sigma > 0 else Xt)
                p_noise[t] = mod.predict_proba(Xp)[:, 1]

            def triple(idx_a, idx_e, idx_r, p_r):
                pa, pe, pr = p_full[idx_a], p_full[idx_e], p_full[idx_r]
                a = pavia.rga_vector(yt[idx_a], pa, GRID)
                e = np.empty(L)
                e[0] = 1.0
                for t in range(1, L):
                    e[t] = rge_score(pe, p_mask[t][idx_e],
                                     class_order=CLASS_ORDER)
                r = np.empty(L)
                for t in range(L):
                    r[t] = rgr_score(pr, p_r[t][idx_r],
                                     class_order=CLASS_ORDER)
                return a, e, r

            # ---- G4 fastpath check at the point estimate
            full_idx = np.arange(n)
            a_chk, e_chk, r_chk = triple(full_idx, full_idx, full_idx, p_swap)
            g4 = {"RGA": float(np.max(np.abs(a_chk - a0))),
                  "RGE": float(np.max(np.abs(e_chk - e0))),
                  "RGR": float(np.max(np.abs(r_chk - r0_swap)))}
            if max(g4.values()) > 1e-12:
                raise SystemExit(f"G4 FAIL {arm}: fastpath gaps {g4}")
            say(f"[G4] {arm} fastpath vs package curves: "
                + " ".join(f"{k} {v:.1e}" for k, v in g4.items()))

            # ---- replicate curve matrices: paired + independent, both families
            Ab = np.empty((B, L)); Eb = np.empty((B, L)); Rb = np.empty((B, L))
            Rb_noise = np.empty((B, L))
            for b in range(B):
                ib = IDX[b]
                a, e, r = triple(ib, ib, ib, p_swap)
                Ab[b], Eb[b], Rb[b] = a, e, r
                pb = p_full[ib]
                for t in range(L):
                    Rb_noise[b, t] = rgr_score(pb, p_noise[t][ib],
                                               class_order=CLASS_ORDER)
            Ai = np.empty((B, L)); Ei = np.empty((B, L)); Ri = np.empty((B, L))
            Ri_noise = np.empty((B, L))
            for b in range(B):
                a, e, r = triple(IND[0, b], IND[1, b], IND[2, b], p_swap)
                Ai[b], Ei[b], Ri[b] = a, e, r
                pr = p_full[IND[2, b]]
                for t in range(L):
                    Ri_noise[b, t] = rgr_score(pr, p_noise[t][IND[2, b]],
                                               class_order=CLASS_ORDER)
            say(f"[bootstrap] {arm}: paired + independent, both families, "
                f"B={B}, {time.time() - t_arm:.1f}s")

            # ---- arms via the Section 6 module's own arm_block
            def build_arms(r0, RbF, RiF, family):
                curves_point = (a0, e0, r0)
                reps_paired = (Ab, Eb, RbF)
                reps_ind = (Ai, Ei, RiF)
                ga, ge, gr = pavia.grad_rms_entries(a0, e0, r0)
                gt_a, gt_e, gt_r = pavia.grad_topsis_entries(
                    a0, e0, r0, pis, nis, wvec)

                def s_mean(A, E, R):
                    return np.column_stack([A.mean(1), E.mean(1), R.mean(1)])

                def s_cbrt(A, E, R):
                    return np.column_stack([np.cbrt(A).mean(1),
                                            np.cbrt(E).mean(1),
                                            np.cbrt(R).mean(1)])

                def proj(gA, gE, gR):
                    def sfn(A, E, R):
                        return np.column_stack([A @ gA, E @ gE, R @ gR])
                    return sfn

                blocks = []
                blocks.append(pavia.arm_block(
                    "arithmetic", f"volume composite, arithmetic ({family})",
                    pavia.v_arith, curves_point, reps_paired, reps_ind,
                    summary_fn=s_mean,
                    grad_fn=lambda s_: np.array([1 / 3, 1 / 3, 1 / 3]),
                    exact_in_summaries=True))
                blocks.append(pavia.arm_block(
                    "geometric", f"volume composite, geometric ({family})",
                    pavia.v_geom, curves_point, reps_paired, reps_ind,
                    summary_fn=s_cbrt,
                    grad_fn=lambda s_: np.array([s_[1] * s_[2],
                                                 s_[0] * s_[2],
                                                 s_[0] * s_[1]]),
                    exact_in_summaries=True))
                blocks.append(pavia.arm_block(
                    "rms", f"volume composite, RMS tensor ({family})",
                    pavia.v_rms, curves_point, reps_paired, reps_ind,
                    summary_fn=proj(ga, ge, gr),
                    grad_fn=lambda s_: np.ones(3), exact_in_summaries=False))
                blocks.append(pavia.arm_block(
                    "topsis", f"TOPSIS closeness, thesis reference ({family})",
                    lambda A, E, R: pavia.topsis_cc(A, E, R, pis, nis, wvec),
                    curves_point, reps_paired, reps_ind,
                    summary_fn=proj(gt_a, gt_e, gt_r),
                    grad_fn=lambda s_: np.ones(3), exact_in_summaries=False))
                return {b_["_name"]: b_ for b_ in blocks}

            arm_res = {
                "point_curves": {"RGA": a0.tolist(), "RGE": e0.tolist(),
                                 "RGR_tail_swap": r0_swap.tolist(),
                                 "RGR_gaussian": [float(rgr_score(
                                     p_full, p_noise[t],
                                     class_order=CLASS_ORDER))
                                     for t in range(L)],
                                 "greedy_removal_order":
                                     [names[j] for j in order]},
                "fastpath_max_abs_gap": g4,
                "curve_summary_corr_paired": {
                    "tail_swap": np.corrcoef(np.column_stack(
                        [Ab.mean(1), Eb.mean(1), Rb.mean(1)]),
                        rowvar=False).tolist(),
                    "gaussian": np.corrcoef(np.column_stack(
                        [Ab.mean(1), Eb.mean(1), Rb_noise.mean(1)]),
                        rowvar=False).tolist(),
                },
                "tail_swap": build_arms(r0_swap, Rb, Ri, "tail-swap family"),
            }
            r0_noise = np.array(arm_res["point_curves"]["RGR_gaussian"])
            arm_res["gaussian_control"] = build_arms(
                r0_noise, Rb_noise, Ri_noise, "gaussian control family")
            results["arms"][arm] = arm_res
            say(f"[arm] {arm} complete in {time.time() - t_arm:.1f}s")

    results["runtime_seconds"] = round(time.time() - t_start, 1)
    stem = "pilot" if args.tag == "pilot" else "production"
    out_json = os.path.join(HERE, f"results-aggregation-{stem}.json")
    with open(out_json, "w") as fh:
        json.dump(results, fh, indent=1)
    with open(os.path.join(HERE, f"run-aggregation-{stem}.log"), "w") as fh:
        fh.write("\n".join(LOG) + "\n")
    say(f"[done] {out_json} in {results['runtime_seconds']}s")


if __name__ == "__main__":
    main()
